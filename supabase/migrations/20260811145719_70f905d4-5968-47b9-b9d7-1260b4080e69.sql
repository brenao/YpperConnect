  alocacao_pct    integer CHECK (alocacao_pct IS NULL OR alocacao_pct BETWEEN 0 AND 100),
  ordem           integer NOT NULL DEFAULT 0,
  concluido_em    timestamptz,
  CHECK (fim >= inicio),
  CHECK (pai_id IS NULL OR pai_id <> id)
);
CREATE INDEX ix_tarefas_projeto ON public.projeto_tarefas (projeto_id, ordem);
CREATE INDEX ix_tarefas_quadro ON public.projeto_tarefas (projeto_id, quadro);
CREATE INDEX ix_tarefas_pai ON public.projeto_tarefas (pai_id);

