-- 1. Listas administraveis -------------------------------------------
CREATE TABLE public.equipes (
  id    text PRIMARY KEY,
  nome  text NOT NULL UNIQUE,
  ativo boolean NOT NULL DEFAULT true
);

CREATE TABLE public.categorias (
  id     text PRIMARY KEY,
  nome   text NOT NULL,
  escopo text NOT NULL CHECK (escopo IN ('chamado','servico','artigo','sistema')),
  ativo  boolean NOT NULL DEFAULT true,
  UNIQUE (escopo, nome)
);

-- 2. Identidade e autorizacao ----------------------------------------
CREATE TABLE public.perfis_acesso (
  id        text PRIMARY KEY,
  nome      text NOT NULL UNIQUE,
  descricao text,
  sistema   boolean NOT NULL DEFAULT false,
  ativo     boolean NOT NULL DEFAULT true
);

CREATE TABLE public.usuarios (
  id              text PRIMARY KEY,
  ad_object_id    text UNIQUE,
  nome            text NOT NULL,
  email           text NOT NULL,
  login           text NOT NULL UNIQUE,
  departamento    text,
  equipe_id       text REFERENCES public.equipes (id),
  perfil_id       text REFERENCES public.perfis_acesso (id),
  origem          text NOT NULL DEFAULT 'manual' CHECK (origem IN ('ad','manual')),
  admin           boolean NOT NULL DEFAULT false,
  ativo           boolean NOT NULL DEFAULT true,
  sincronizado_em timestamptz,
  criado_em       timestamptz NOT NULL DEFAULT now(),
  atualizado_em   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_usuarios_email ON public.usuarios (email);
CREATE INDEX ix_usuarios_ativo ON public.usuarios (ativo);
CREATE INDEX ix_usuarios_equipe ON public.usuarios (equipe_id);

CREATE TABLE public.perfil_modulos (
  perfil_id  text NOT NULL REFERENCES public.perfis_acesso (id) ON DELETE CASCADE,
  modulo_key text NOT NULL,
  PRIMARY KEY (perfil_id, modulo_key)
);

CREATE TABLE public.perfil_features (
  perfil_id   text NOT NULL REFERENCES public.perfis_acesso (id) ON DELETE CASCADE,
  feature_key text NOT NULL,
  PRIMARY KEY (perfil_id, feature_key)
);

-- 3. Catalogo, sistemas e conhecimento -------------------------------
CREATE TABLE public.servicos (
  id            text PRIMARY KEY,
  nome          text NOT NULL,
  categoria_id  text REFERENCES public.categorias (id),
  descricao     text,
  tipo_padrao   text NOT NULL CHECK (tipo_padrao IN ('incidente','requisicao','melhoria','problema','tarefa')),
  sla_horas     integer NOT NULL CHECK (sla_horas > 0),
  equipe_id     text REFERENCES public.equipes (id),
  gerado_por_ia boolean NOT NULL DEFAULT false,
  ativo         boolean NOT NULL DEFAULT true,
  criado_em     timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_servicos_categoria ON public.servicos (categoria_id);
CREATE INDEX ix_servicos_ativo ON public.servicos (ativo);

CREATE TABLE public.sistemas (
  id             text PRIMARY KEY,
  nome           text NOT NULL UNIQUE,
  descricao      text,
  categoria_id   text REFERENCES public.categorias (id),
  responsavel_id text REFERENCES public.usuarios (id),
  atribuicao_id  text REFERENCES public.usuarios (id),
  equipe_id      text REFERENCES public.equipes (id),
  criticidade    text NOT NULL CHECK (criticidade IN ('alta','media','baixa')),
  ativo          boolean NOT NULL DEFAULT true
);
CREATE INDEX ix_sistemas_responsavel ON public.sistemas (responsavel_id);
CREATE INDEX ix_sistemas_equipe ON public.sistemas (equipe_id);

CREATE TABLE public.artigos (
  id            text PRIMARY KEY,
  titulo        text NOT NULL,
  categoria_id  text REFERENCES public.categorias (id),
  resumo        text,
  conteudo      text NOT NULL,
  status        text NOT NULL DEFAULT 'rascunho' CHECK (status IN ('publicado','revisar','rascunho')),
  visualizacoes integer NOT NULL DEFAULT 0,
  gerado_por_ia boolean NOT NULL DEFAULT false,
  autor_id      text REFERENCES public.usuarios (id),
  criado_em     timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_artigos_status ON public.artigos (status);
CREATE INDEX ix_artigos_categoria ON public.artigos (categoria_id);

-- 4. Chamados ---------------------------------------------------------
CREATE TABLE public.chamados (
  id                     text PRIMARY KEY,
  numero                 bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) UNIQUE,
  prefixo                text NOT NULL DEFAULT 'CHM',
  codigo                 text GENERATED ALWAYS AS (prefixo || '-' || numero::text) STORED,
  titulo                 text NOT NULL,
  descricao              text NOT NULL,
  tipo                   text NOT NULL CHECK (tipo IN ('incidente','requisicao','melhoria','problema','tarefa')),
  categoria_id           text REFERENCES public.categorias (id),
  servico_id             text REFERENCES public.servicos (id),
  sistema_id             text REFERENCES public.sistemas (id),
  impacto                text NOT NULL CHECK (impacto IN ('alto','medio','baixo')),
  urgencia               text NOT NULL CHECK (urgencia IN ('alta','media','baixa')),
  prioridade             text NOT NULL CHECK (prioridade IN ('P1','P2','P3','P4')),
  status                 text NOT NULL DEFAULT 'novo' CHECK (status IN ('novo','triagem','em_andamento','aguardando','resolvido','fechado')),
  solicitante_id         text NOT NULL REFERENCES public.usuarios (id),
  responsavel_id         text REFERENCES public.usuarios (id),
  equipe_id              text REFERENCES public.equipes (id),
  origem                 text NOT NULL CHECK (origem IN ('portal','ia','email','telefone')),
  problema_vinculado_id  text REFERENCES public.chamados (id),
  descricao_encerramento text,
  criado_em              timestamptz NOT NULL DEFAULT now(),
  atualizado_em          timestamptz NOT NULL DEFAULT now(),
  prazo_resposta         timestamptz,
  prazo_sla              timestamptz NOT NULL,
  respondido_em          timestamptz,
  resolvido_em           timestamptz,
  fechado_em             timestamptz
);
CREATE UNIQUE INDEX ux_chamados_codigo ON public.chamados (codigo);
CREATE INDEX ix_chamados_status_prazo ON public.chamados (status, prazo_sla);
CREATE INDEX ix_chamados_responsavel ON public.chamados (responsavel_id, status);
CREATE INDEX ix_chamados_solicitante ON public.chamados (solicitante_id, criado_em);
CREATE INDEX ix_chamados_servico ON public.chamados (servico_id);
CREATE INDEX ix_chamados_sistema ON public.chamados (sistema_id);
CREATE INDEX ix_chamados_criado ON public.chamados (criado_em);
CREATE INDEX ix_chamados_equipe_status ON public.chamados (equipe_id, status);

CREATE TABLE public.chamado_interacoes (
  id         text PRIMARY KEY,
  chamado_id text NOT NULL REFERENCES public.chamados (id) ON DELETE CASCADE,
  autor_id   text REFERENCES public.usuarios (id),
  tipo       text NOT NULL CHECK (tipo IN ('comentario','nota_interna','email')),
  corpo      text NOT NULL,
  criado_em  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_interacoes_chamado ON public.chamado_interacoes (chamado_id, criado_em);

CREATE TABLE public.chamado_historico (
  id             text PRIMARY KEY,
  chamado_id     text NOT NULL REFERENCES public.chamados (id) ON DELETE CASCADE,
  autor_id       text REFERENCES public.usuarios (id),
  campo          text NOT NULL,
