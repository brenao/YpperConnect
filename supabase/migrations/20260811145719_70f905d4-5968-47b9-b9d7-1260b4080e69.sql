-- 6. Projetos ---------------------------------------------------------
CREATE TABLE public.projetos (
  id            text PRIMARY KEY,
  nome          text NOT NULL,
  objetivo      text,
  sponsor_id    text REFERENCES public.usuarios (id),
  gerente_id    text REFERENCES public.usuarios (id),
  status        text NOT NULL DEFAULT 'planejamento' CHECK (status IN ('planejamento','execucao','paralisado','cancelado','concluido')),
  inicio        date NOT NULL,
  fim           date NOT NULL CHECK (fim >= inicio),
  criado_em     timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_projetos_status ON public.projetos (status);
CREATE INDEX ix_projetos_gerente ON public.projetos (gerente_id);

CREATE TABLE public.projeto_tarefas (
  id              text PRIMARY KEY,
  projeto_id      text NOT NULL REFERENCES public.projetos (id) ON DELETE CASCADE,
  pai_id          text REFERENCES public.projeto_tarefas (id) ON DELETE CASCADE,
  nome            text NOT NULL,
  atividade       text,
  inicio          date NOT NULL,
  fim             date NOT NULL,
  progresso       integer NOT NULL DEFAULT 0 CHECK (progresso BETWEEN 0 AND 100),
  quadro          text NOT NULL DEFAULT 'backlog' CHECK (quadro IN ('backlog','todo','doing','done')),
  marco           boolean NOT NULL DEFAULT false,
