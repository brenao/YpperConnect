CREATE INDEX ix_historico_chamado ON public.chamado_historico (chamado_id, criado_em);
CREATE INDEX ix_historico_campo ON public.chamado_historico (campo, criado_em);

-- 5. Recursos ---------------------------------------------------------
CREATE TABLE public.recursos (
  id                       text PRIMARY KEY,
